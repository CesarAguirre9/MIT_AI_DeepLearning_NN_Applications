def single_neuron_classification_model(w,w_0,x):
    z = 0 
    for feature, weight in zip(x,w):
        z += feature * weight
    z += w_0

    # We can apply our activation function 
    a = sigmoid(z)
    return a

def sigmoid(z):
    non_zero_tolerance = 1e-8
    return 1/(1 + math.exp(-z) + non_zero_tolerance)

# train the model...
learning_rate = 0.001
epochs = 200

def train_model_NLL_loss(model_function, w, w_0, input_data,
                         output_data, learning_rate, num_epochs):
    non_zero_tolerance = 1e-8
    for epoch in range(num_epochs):
        total_loss = 0
        for x, y in zip(input_data, output_data):
            y_predicted = model_function(w, w_0, x)
            nll_loss = -(y * math.log(y_predicted + non_zero_tolerance)+ (1-y) * math.log(1-y_predicted + non_zero_tolerance))
            total_loss += nll_loss

            w_0 -= learning_rate * (y_predicted - y) # We should also update the bias using gradient

            for j,x_j in enumerate(x):
                w[j] -= learning_rate * (y_predicted - y) * x_j

        report_every = max(1,num_epochs // 10)

        if epoch % report_every == 0:
            print("epoch",epoch, "has total loss", total_loss)
    return w, w_0

class SingleNeuronCLassifier:
    def __init__(self,w,w_0):
        self.w = w
        self.w_0 = w_0
    def forward(self,x):
        return single_neuron_classification_model(self.w, self.w_0,x)


# We will use this function to evaluate how well our trained classifier perfom
